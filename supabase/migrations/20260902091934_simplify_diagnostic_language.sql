update public.diagnostic_questions as question
set
  prompt = copy.prompt,
  guidance = copy.guidance,
  evidence_examples = copy.evidence_examples
from public.diagnostic_questionnaires as questionnaire
join (values
  (1,
   '¿En tu web o perfil principal se entiende rápidamente qué vendes y para quién?',
   'Piensa en alguien que no conoce tu negocio. ¿Puede saber qué ofreces, a qué tipo de cliente ayudas, dónde trabajas y cómo contactarte?',
   'Comprueba: servicios visibles, tipo de cliente, zona, motivo para elegirte y botón de contacto.'),
  (2,
   '¿Tienes actualizados y bajo control tu web, dominio, ficha de Google y redes?',
   'Valora solo los canales que utilizas. Debes saber quién tiene las claves y cuándo se revisaron por última vez los horarios, teléfonos, servicios y enlaces.',
   'Comprueba: accesos guardados, responsables claros y datos iguales y correctos en todos tus canales.'),
  (3,
   '¿Te encuentran en Google al buscar tu servicio, sin escribir el nombre de tu empresa?',
   'Haz una búsqueda como la haría un cliente: servicio o problema más ciudad o zona. No busques el nombre exacto de la empresa.',
   'Comprueba: aparición en Google o Maps, visitas desde búsquedas y consultas recibidas por ese canal.'),
  (4,
   '¿Es fácil contactarte, pedir presupuesto, reservar o comprar desde el móvil?',
   'Prueba el recorrido completo con un teléfono. La acción principal debe verse rápido y pedir solo la información necesaria.',
   'Comprueba: botón visible, WhatsApp o teléfono correcto, formulario breve, reserva o compra sin errores.'),

  (5,
   '¿Recibes consultas o solicitudes de presupuesto por internet?',
   'Cuenta contactos con una necesidad real, no seguidores, visitas o reacciones en redes. Piensa en un mes normal.',
   'Comprueba: formularios, llamadas desde Google, WhatsApp, mensajes, reservas o solicitudes de presupuesto.'),
  (6,
   '¿Anotas de dónde llegó cada consulta?',
   'Piensa en las consultas reales. Debes poder distinguir si llegaron por Google, redes, anuncios, la web, una recomendación u otro canal.',
   'Comprueba: campo de origen en una lista o CRM, enlaces de campaña, llamadas registradas o pregunta “¿cómo nos conociste?”.'),
  (7,
   '¿Haces acciones concretas para conseguir nuevos clientes por internet?',
   'Cuenta acciones con un público, una oferta y una fecha, no publicaciones sueltas sin un objetivo comercial claro.',
   'Comprueba: campaña local, promoción, serie de contenidos, anuncio, colaboración o acción en Google o redes.'),
  (8,
   '¿Sabes qué acciones digitales te traen consultas o ventas?',
   'Compara resultados reales entre acciones o canales. Si pagas publicidad, incluye también cuánto cuesta conseguir una consulta o una venta.',
   'Comprueba: consultas, presupuestos, ventas, conversión y coste por resultado de cada acción.'),

  (9,
   '¿Tienes claros los pasos desde que alguien pregunta hasta que compra?',
   'Piensa en las etapas reales de una venta. Cada persona debería saber cuándo una oportunidad avanza y qué debe ocurrir después.',
   'Comprueba: contacto nuevo, necesidad confirmada, presupuesto enviado, seguimiento, venta ganada o perdida.'),
  (10,
   '¿Anotas cada posible venta, quién la atiende y cuál es el siguiente paso?',
   'Una consulta no está controlada si queda solo en el correo, WhatsApp, teléfono o memoria de una persona.',
   'Comprueba: lista, tablero o CRM con cliente, fecha, estado, responsable y próxima acción.'),
  (11,
   '¿Respondes y haces seguimiento a las consultas sin dejar ninguna olvidada?',
   'Valora cuánto tardas en responder y si vuelves a contactar cuando el posible cliente no contesta o todavía no decide.',
   'Comprueba: aviso de nueva consulta, plazo de respuesta, recordatorios y varios intentos de seguimiento.'),
  (12,
   '¿Sabes en qué paso se pierden más ventas y por qué?',
   'Revisa cuántas oportunidades avanzan entre etapas y anota motivos concretos de pérdida, como precio, plazo, competencia o falta de respuesta.',
   'Comprueba: ventas ganadas y perdidas, tiempo hasta cerrar, paso con más abandonos y motivos registrados.'),

  (13,
   '¿Reúnes las consultas de clientes en un lugar donde se puedan seguir?',
   'Incluye correo, llamadas, WhatsApp, redes y formularios. Debe ser fácil ver qué está pendiente y quién responde.',
   'Comprueba: bandeja compartida, CRM, lista de incidencias o sistema con responsable y estado.'),
  (14,
   '¿Puede un cliente contratar, reservar o empezar el servicio sin pasos confusos?',
   'Recorre desde que acepta hasta que recibe el servicio. Valora si entiende qué debe hacer, qué documentos necesita y qué ocurrirá después.',
   'Comprueba: presupuesto claro, firma o aceptación, pago, cita, confirmación y mensaje de bienvenida.'),
  (15,
   '¿Pides opiniones a tus clientes y corriges los problemas que se repiten?',
   'No cuentes solo comentarios espontáneos. Debe existir una forma habitual de pedir opinión y revisar las quejas repetidas.',
   'Comprueba: solicitud de reseña, encuesta breve, llamada posterior, incidencias agrupadas y acciones de mejora.'),
  (16,
   '¿Vuelves a contactar a clientes para que repitan o te recomienden?',
   'Adapta la respuesta a tu negocio: nueva compra, renovación, mantenimiento, servicio complementario o recomendación.',
   'Comprueba: recordatorios, seguimiento posventa, renovaciones, ofertas para clientes o petición de recomendación.'),

  (17,
   '¿Revisas regularmente datos básicos de visitas, consultas y ventas?',
   'No hace falta un panel complejo. Debes poder ver, al menos una vez al mes, cuántas personas llegan, preguntan y compran.',
   'Comprueba: visitas o alcance, consultas, presupuestos, ventas, importe medio y canal de origen.'),
  (18,
   '¿Tus herramientas pasan datos entre sí sin copiarlos a mano?',
   'Piensa en la web, formularios, agenda, contactos, presupuestos y facturas. Cuenta solo conexiones que funcionan en el trabajo diario.',
   'Comprueba: formulario que crea un contacto, reserva que entra al calendario o venta que pasa a facturación.'),
  (19,
   '¿Alguna tarea repetitiva se hace automáticamente?',
   'Cuenta tareas completas que se ejecutan solas y se revisan cuando es necesario, no una plantilla que alguien debe copiar cada vez.',
   'Comprueba: avisos, recordatorios, asignación de consultas, documentos, seguimiento o petición de reseña.'),
  (20,
   '¿Compruebas si esas automatizaciones ahorran tiempo o evitan errores?',
   'Compara el resultado con cómo se hacía antes. Revisa también cuándo falla y si una persona debe intervenir.',
   'Comprueba: tiempo ahorrado, tareas terminadas, errores, consultas atendidas a tiempo y fallos detectados.'),

  (21,
   '¿Tienes un objetivo digital concreto para los próximos meses?',
   'Debe indicar qué quieres conseguir, cuánto, para cuándo y quién se encargará. “Mejorar internet” o “vender más” no es suficiente.',
   'Comprueba: número de consultas o ventas, fecha, responsable, presupuesto o tiempo disponible.'),
  (22,
   '¿Revisáis qué ocurre desde la primera consulta hasta la venta y la atención posterior?',
   'Si trabajas solo, piensa si haces esta revisión de forma periódica. Si sois varios, comprobad que marketing, ventas y atención compartan la información.',
   'Comprueba: revisión mensual, problemas detectados, decisiones anotadas, responsable y fecha de la siguiente revisión.'),
  (23,
   '¿Sabes usar bien las herramientas digitales necesarias para tu trabajo?',
   'Piensa en tareas reales. Si hay más personas, valora si cada una domina las herramientas que necesita para su función.',
   'Comprueba: formación aplicada a web, CRM, analítica, contenidos, campañas, facturación o atención al cliente.'),
  (24,
   '¿Proteges las cuentas y datos del negocio con medidas básicas de seguridad?',
   'Valora lo que haces habitualmente: cuentas individuales, contraseñas seguras, doble verificación, copias y retirada de accesos antiguos.',
   'Comprueba: doble factor, gestor de contraseñas, permisos, copias verificadas y control de altas y bajas.')
) as copy(position, prompt, guidance, evidence_examples) on true
where question.questionnaire_id = questionnaire.id
  and questionnaire.slug = 'nexaro-inicial'
  and questionnaire.version = 3
  and question.position = copy.position;

update public.diagnostic_questionnaires
set
  title = 'Diagnóstico inicial de tu negocio',
  description = '24 preguntas sencillas para conocer cómo te encuentran, cómo conviertes consultas en ventas y qué necesitas mejorar primero.'
where slug = 'nexaro-inicial'
  and version = 3;
